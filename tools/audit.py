"""Writes reports/AUDIT.md: every squad (all factions) -> entities -> weapons -> treatment."""
import os, sys, glob, csv, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); sys.path.insert(0, HERE)
import rgd; from flat import flat_idx; rgd.load_dict()
A = os.path.join(ROOT, 'extracted_assets', 'attrib', 'attrib'); MODA = os.path.join(ROOT, 'modified', 'attrib', 'attrib')
def idx(folder):
    r = {}
    for base in (A, MODA):
        for f in glob.glob(os.path.join(base, folder, '**', '*.rgd'), recursive=True): r[os.path.basename(f)[:-4]] = f
    return r
E = idx('ebps'); W = idx('weapon'); S = idx('slot_item')
gun = {r['file'].split('/')[-1][:-4]: r for r in csv.DictReader(open(os.path.join(ROOT, 'reports', 'gunfire_changes.csv')))}
rng = {r['file'].split('/')[-1][:-4]: r for r in csv.DictReader(open(os.path.join(ROOT, 'reports', 'ranges_changes.csv')))}
radio_sq = {r['file'] for r in csv.DictReader(open(os.path.join(ROOT, 'reports', 'radio_changes.csv'))) if r['what'] == 'squad'}
def weapons_of_entity(name):
    f = E.get(name); out = []
    if not f: return out
    for k, v in flat_idx(rgd.load(f)[1]).items():
        if k.endswith('/weapon_table/weapon/weapon') and v: out.append(v.split(':')[-1])
    return out
def treat(w):
    t = []
    if w in gun: t.append('gunfire: ' + ('subtle infantry bullet' if gun[w]['class'] == 'infantry' else 'Kriegspiel MG bullet kept (visible tracer)'))
    if w in rng: t.append('range %s->%s' % (rng[w]['old_max'], rng[w]['new_max']))
    if '_vplus_radio' in w: t.append('Radio Man weapon')
    if w not in W: t.append('vanilla weapon (not overridden by Kriegspiel)')
    return '; '.join(t) or 'unchanged'
L = ['# Vanilla+ all-faction audit', '', 'Generated by tools/audit.py from the actual build. Every squad blueprint shipped by Kriegspiel V5 is listed with the weapons of its entities and what Vanilla+ did to each weapon.', '']
by_fac = collections.defaultdict(list); seen_w = set(); unverified = []
for f in sorted(glob.glob(os.path.join(A, 'sbps', '**', '*.rgd'), recursive=True)):
    rel = os.path.relpath(f, A).replace('\\', '/'); parts = rel.split('/')
    fac = parts[2] if len(parts) > 3 and parts[1] == 'races' else 'other'
    mf = os.path.join(MODA, rel); d = flat_idx(rgd.load(mf if os.path.exists(mf) else f)[1])
    ents = [v.split(':')[-1] for k, v in d.items() if k.startswith('/squad_loadout_ext/unit_list') and k.endswith('/type')]
    ws = []
    for e in ents:
        if e not in E: unverified.append((rel, e))
        ws += weapons_of_entity(e)
    for w in ws: seen_w.add(w)
    by_fac[fac].append((rel, ents, sorted(set(ws)), rel in radio_sq))
for fac in sorted(by_fac):
    L += ['## ' + fac, '', '| squad | entities | weapons -> treatment | Radio Man |', '|---|---|---|---|']
    for rel, ents, ws, rad in by_fac[fac]:
        L.append('| `%s` | %s | %s | %s |' % (rel.split('/')[-1][:-4], ', '.join(sorted(set(ents))) or '-',
                 '<br>'.join('`%s` - %s' % (w, treat(w)) for w in ws) or '-', 'yes' if rad else ''))
    L.append('')
L += ['## Bullet weapons not mounted on any squad entity directly', '',
      'These are carried as slot items / upgrades / abilities; they get the same treatment through their weapon file:', '']
L += ['- `%s` (%s) - %s' % (w, gun[w]['class'], treat(w)) for w in sorted(gun) if w not in seen_w]
L += ['', '## Entities that could not be inspected', '',
      'Squads whose entity blueprint is not in Kriegspiel V5 (the game uses the vanilla entity, which uses vanilla hitscan weapons - nothing for Vanilla+ to change):', '']
L += ['- `%s` -> `%s`' % u for u in sorted(set(unverified))] or ['- none']
open(os.path.join(ROOT, 'reports', 'AUDIT.md'), 'w').write('\n'.join(L) + '\n')
print('factions', {k: len(v) for k, v in by_fac.items()}, 'unverified', len(set(unverified)), 'weapons seen', len(seen_w))
